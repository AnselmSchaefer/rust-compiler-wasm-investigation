//! Writes Cargo.lock exactly as cargo 1.99 does (`ops/lockfile.rs` `serialize_resolve` and
//! `resolver/encode.rs`): packages sorted by name, version, source; the root without source or
//! checksum; a dependency written as `name`, or `name version` when several versions of that
//! name are locked (plus ` (source)` when even that is ambiguous), sorted as strings.

use crate::resolve::Resolve;
use crate::summary::{CRATES_IO_SOURCE, Source};
use std::collections::{BTreeMap, HashMap};
use std::fmt::Write;

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
pub enum LockVersion {
    V1,
    V2,
    V3,
    V4,
}

/// cargo's `ResolveVersion::with_rust_version`: the newest format the root's MSRV can read.
pub fn lock_version(rust_version: Option<&cargo_util_schemas::manifest::RustVersion>) -> LockVersion {
    let Some(rv) = rust_version else { return LockVersion::V4 };
    let p = rv.to_partial();
    let at_least = |minor: u64| (p.major, p.minor.unwrap_or(0)) >= (1, minor);
    if at_least(83) {
        LockVersion::V4
    } else if at_least(53) {
        LockVersion::V3
    } else if at_least(41) {
        LockVersion::V2
    } else {
        LockVersion::V1
    }
}

fn source_str(s: Source) -> Option<&'static str> {
    match s {
        Source::Path => None,
        Source::Registry => Some(CRATES_IO_SOURCE),
    }
}

/// A TOML basic string, as the `toml` crate prints simple values.
fn quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c == '\u{7f}' => {
                let _ = write!(out, "\\u{:04X}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

pub fn write_lockfile(resolve: &Resolve) -> String {
    write_lockfile_version(resolve, lock_version(resolve.rust_version.as_ref()))
}

pub fn write_lockfile_version(resolve: &Resolve, version: LockVersion) -> String {
    let pkgs = &resolve.packages;
    // name → version → how many packages (v2+ shortens dependency entries with this).
    let mut counts: HashMap<&str, HashMap<&semver::Version, usize>> = HashMap::new();
    for p in pkgs {
        *counts.entry(&p.name).or_default().entry(&p.version).or_default() += 1;
    }
    // (name, version, source), each part only when needed; sorts like cargo's derived Ord.
    let encode = |i: usize| -> (String, Option<String>, Option<&'static str>) {
        let p = &pkgs[i];
        let mut v = Some(p.version.to_string());
        let mut src = source_str(p.source);
        if version >= LockVersion::V2 {
            let vc = &counts[&*p.name];
            if vc[&p.version] == 1 {
                src = None;
                if vc.len() == 1 {
                    v = None;
                }
            }
        }
        (p.name.to_string(), v, src)
    };
    let display = |(n, v, s): &(String, Option<String>, Option<&str>)| {
        let mut out = n.clone();
        if let Some(v) = v {
            let _ = write!(out, " {v}");
        }
        if let Some(s) = s {
            let _ = write!(out, " ({s})");
        }
        out
    };

    let mut out = String::from("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n");
    match version {
        LockVersion::V3 => out.push_str("version = 3\n\n"),
        LockVersion::V4 => out.push_str("version = 4\n\n"),
        _ => {}
    }
    for p in pkgs {
        out.push_str("[[package]]\n");
        let _ = writeln!(out, "name = {}", quote(&p.name));
        let _ = writeln!(out, "version = {}", quote(&p.version.to_string()));
        if let Some(s) = source_str(p.source) {
            let _ = writeln!(out, "source = {}", quote(s));
        }
        if version >= LockVersion::V2 {
            if let Some(c) = &p.checksum {
                let _ = writeln!(out, "checksum = {}", quote(c));
            }
        }
        let mut deps: Vec<_> = p.deps.iter().map(|&d| encode(d)).collect();
        deps.sort();
        if !deps.is_empty() {
            out.push_str("dependencies = [\n");
            for d in &deps {
                let _ = writeln!(out, " {},", quote(&display(d)));
            }
            out.push_str("]\n");
        }
        out.push('\n');
    }
    if version == LockVersion::V1 {
        // v1 keeps checksums in [metadata], keyed by the full package id.
        let meta: BTreeMap<String, &str> = pkgs
            .iter()
            .enumerate()
            .filter(|(_, p)| p.source != Source::Path)
            .map(|(i, p)| {
                let (n, _, s) = encode(i);
                (format!("checksum {}", display(&(n, Some(p.version.to_string()), s))), p.checksum.as_deref().unwrap_or("<none>"))
            })
            .collect();
        if !meta.is_empty() {
            out.push_str("[metadata]\n");
            for (k, v) in meta {
                let _ = writeln!(out, "{} = {}", quote(&k), quote(v));
            }
        }
    } else {
        while out.ends_with("\n\n") {
            out.pop();
        }
    }
    out
}
