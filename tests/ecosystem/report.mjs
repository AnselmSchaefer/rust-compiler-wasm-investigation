// WP-22: the ecosystem table. Joins the native baseline (build/wp-22/native.json, native.sh) and
// the browser run (build/wp-22/browser.json, tests/e2e/ecosystem.spec.ts) into a markdown table
// with a reason class per failure, and prints the pass rate.
//   node tests/ecosystem/report.mjs [list.json] [out.md]
// A crate that doesn't build natively for wasm32-wasip1 either is class `target` and doesn't count:
// the browser can't do better than cargo for the same target. The rate is over the rest.
import { readFileSync, writeFileSync } from 'node:fs';

const [listFile = 'tests/ecosystem/top100.json', outFile = 'tests/ecosystem/results.md'] = process.argv.slice(2);
const list = JSON.parse(readFileSync(listFile, 'utf8'));
const native = JSON.parse(readFileSync('build/wp-22/native.json', 'utf8'));
const browser = JSON.parse(readFileSync('build/wp-22/browser.json', 'utf8'));

/** First matching class for a failed browser build's error text. */
const CLASSES = [
  ['timeout', /^timeout after/m],
  ['host error', /^(exception|page): /m],
  ['resolve', /failed to select a version|failed to resolve|no matching package/],
  ['build script runs a program', /failed to run custom build command[\s\S]*not found \(a build script in the sandbox can only run rustc\)/],
  ['build script trap', /failed to run custom build command[\s\S]*(wasm trap|exit 134)/],
  ['build script error', /failed to run custom build command/],
  ['rustc ICE', /internal compiler error|the compiler unexpectedly panicked/],
  ['trap / memory', /wasm trap|RuntimeError|out of memory|memory allocation/i],
  ['proc macro', /proc[-_ ]macro/i],
  ['compile error', /could not compile/],
];
const classify = err => (CLASSES.find(([, re]) => re.test(err)) ?? ['other'])[0];
const firstError = err => (String(err).split('\n').find(l => /^error/.test(l)) ?? String(err).split('\n')[0]).slice(0, 160).replace(/\|/g, '\\|');

const rows = [], counts = {};
let eligible = 0, passed = 0;
for (const c of list.crates) {
  const n = native[c.name], b = browser[c.name];
  let cls, note = '';
  if (!b) cls = 'not run';
  else if (!n?.ok) { cls = 'target'; note = `native: ${firstError(n?.error ?? '')}`; }
  else if (b.ok) cls = 'ok';
  else { cls = classify(b.errors ?? ''); note = firstError(b.errors ?? ''); }
  if (cls !== 'target' && cls !== 'not run') { eligible++; if (cls === 'ok') passed++; }
  counts[cls] = (counts[cls] ?? 0) + 1;
  rows.push(`| ${c.rank} | ${c.name} ${c.version} | ${n?.ok ? 'ok' : 'fail'} | ${b ? (b.ok ? 'ok' : 'fail') : '–'} | ${cls} | ${b?.wallMs ? (b.wallMs / 1000).toFixed(1) : ''} | ${note} |`);
}
const rate = eligible ? (100 * passed / eligible).toFixed(1) : '0';
const md = `# Ecosystem matrix (WP-22)

Generated by \`tests/ecosystem/report.mjs\` from \`build/wp-22/native.json\` (\`tests/ecosystem/native.sh\`) and \`build/wp-22/browser.json\` (\`ECO=1 pnpm exec playwright test tests/e2e/ecosystem.spec.ts --project=chromium\`). List: \`${listFile}\` (crates.io by downloads, fetched ${list.fetched}); each crate at its newest stable version with default features, as a dependency of an empty lib; index: \`tests/ecosystem/index-snapshot.tar.zst\`.

**Browser pass rate: ${passed}/${list.crates.length} = ${(100 * passed / list.crates.length).toFixed(1)}%** of the list; ${passed}/${eligible} = ${rate}% of the crates that build natively for wasm32-wasip1 (${list.crates.length - eligible} fail natively too: class \`target\`).

| Class | Crates |
|---|---|
${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

| # | Crate | Native | Browser | Class | Browser s | Note |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(outFile, md);
console.log(`browser ${passed}/${list.crates.length} of the list, ${passed}/${eligible} = ${rate}% of the natively buildable; classes: ${JSON.stringify(counts)}`);
writeFileSync('build/wp-22/summary.json', JSON.stringify({ total: list.crates.length, eligible, passed, counts }));
