#!/usr/bin/env bash
# Build Clippy, rustfmt and rustdoc's crates for the wasm32-wasip1-threads host (WP-26), with the
# bootstrap config of toolchain/build-rustc.sh: stage 0 (native) compiles them against the stage-1
# compiler crates for the wasm host, as for rustc. No source changes. Resumable (cargo is
# incremental); ≤ 2 h per run.
#
# One gap in bootstrap for a wasm host: the sysroot it assembles for tool builds has every compiler
# crate but rustc_driver, whose stamp keeps only its dylib (wasm has none; the rlib is what
# toolchain/build-rustc-multi.sh links). So for this build only, `build.rustc` is a wrapper around
# the same stage-0 rustc that adds rustc_driver's directory to the search path of tool crates (a
# plain `-L`: `crate=` paths serve only `extern crate`, `dependency=` ones only what other crates
# depend on, and tool crates need both).
# Cargo doesn't see the flag, so the compiler crates stay fresh. The tools' own binaries can't link
# against that sysroot (rmeta only); the lib crates (clippy_lints, rustfmt_nightly, rustdoc) are
# what build-rustc-multi.sh links into rustc-multi, so the final link errors are expected.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${RUSTC_WASM_OUT:-$ROOT/build/rustc-wasm}"
[ -f "$OUT/bootstrap.toml" ] || { echo "no $OUT/bootstrap.toml: run toolchain/build-rustc.sh config" >&2; exit 1; }
REL="$OUT/build/x86_64-unknown-linux-gnu/stage1-rustc/wasm32-wasip1-threads/release"
DRIVER=$(ls -t "$REL"/build/rustc_driver/*/out/librustc_driver-*.rlib | head -1)
REAL=$(sed -n 's/^rustc = "\(.*\)"$/\1/p' "$OUT/bootstrap.toml")
W="$OUT/tools-rustc/bin"
mkdir -p "$W"
cat > "$W/rustc" <<SH
#!/usr/bin/env bash
# Generated by toolchain/build-rustc-tools.sh: stage-0 rustc, plus rustc_driver for tool crates.
case "\${CARGO_MANIFEST_DIR:-}" in
  */src/tools/*|*/src/librustdoc*) exec "$REAL" "\$@" -L "$(dirname "$DRIVER")" ;;
  *) exec "$REAL" "\$@" ;;
esac
SH
chmod +x "$W/rustc"
sed "s#^rustc = \".*\"#rustc = \"$W/rustc\"#" "$OUT/bootstrap.toml" > "$OUT/bootstrap-tools.toml"
export CFLAGS_wasm32_wasip1_threads="-pthread -D_WASI_EMULATED_MMAN"
export CXXFLAGS_wasm32_wasip1_threads="-pthread -D_WASI_EMULATED_MMAN"
cd "$ROOT/build/rust"
# One invocation per tool: bootstrap stops at the first failure, and each tool's binary link fails.
for t in clippy rustfmt rustdoc; do
  ./x build --config "$OUT/bootstrap-tools.toml" --stage 1 "src/tools/$t" -j 10 "$@" || true
done
# The libs are the result; report what's there.
T="$OUT/build/x86_64-unknown-linux-gnu/stage1-tools/wasm32-wasip1-threads/release/build"
for c in clippy_lints clippy_utils clippy_config rustfmt_nightly rustdoc; do
  f=$(ls -t "$T"/$c/*/out/lib$c-*.rlib 2>/dev/null | head -1) || true
  echo "$c: ${f:-MISSING}"
done
