#!/usr/bin/env bash
# Build rustc 1.99.1 for a wasm32-wasip1-threads host (WP-05), against the LLVM from build-llvm.sh.
# Resumable (cargo/bootstrap are incremental); run in the background under systemd-inhibit, ≤ 2 h
# per invocation. Logs: build-logs/wp-05/.
#
#   toolchain/build-rustc.sh            build stage-1 compiler/rustc for the wasm host
#   toolchain/build-rustc.sh config     only (re)write the bootstrap config
#
# The rust checkout (build/rust) is not modified by this script: the bootstrap config and the build
# directory live outside it (build/rustc-wasm/). Source changes to rustc are made by a human (see
# ~/Projects/rustc-wasm-host-source-changes.md and rust's AGENTS.md) as *uncommitted* working-tree
# edits: then HEAD stays at the 1.99.1 release commit, the compiler's version string equals stable
# 1.99.1's exactly, and it accepts rustup's prebuilt wasm32-wasip1 std (danlapid's technique).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
. "$ROOT/toolchain/versions.env"
TAG=$RUST_TAG
RUST="$ROOT/build/rust"
OUT="${RUSTC_WASM_OUT:-$ROOT/build/rustc-wasm}" # another dir: a second, independent build (WP-10 reproducibility)
LLVM="$ROOT/build/llvm-wasm-install"
WASI_SDK="${WASI_SDK_PATH:-$HOME/opt/wasi-sdk}"
HOST=wasm32-wasip1-threads
# Stage 0 is the pinned rustup toolchain of the same version; it needs std for the host target.
rustup toolchain install --profile minimal "$TAG" >/dev/null 2>&1
rustup target add --toolchain "$TAG" "$HOST" wasm32-wasip1 >/dev/null 2>&1
STABLE="$(rustc +$TAG --print sysroot)"
# Stage 0 for the compiler build: the same toolchain with a panic=unwind std for the host (WP-07).
STAGE0="$("$ROOT/toolchain/build-host-std.sh")"
mkdir -p "$OUT"

if [ ! -d "$RUST/.git" ]; then
  git clone -q --depth 1 --branch "$TAG" https://github.com/rust-lang/rust.git "$RUST"
fi
# The only submodule the compiler build needs (bootstrap's own submodule handling is off).
git -C "$RUST" submodule update -q --init --depth 1 library/backtrace

release="$(git -C "$RUST" rev-parse "$TAG^{commit}")"
if [ "$(git -C "$RUST" rev-parse HEAD)" != "$release" ]; then
  echo "build/rust HEAD is not the $TAG release commit; keep rustc changes uncommitted (see header)." >&2
  exit 1
fi
[ -x "$LLVM/bin/llvm-config" ] || { echo "no $LLVM/bin/llvm-config: run toolchain/build-llvm.sh" >&2; exit 1; }

# Permission bits for wasi-libc's stat family (see the source); linked into rustc.wasm with --wrap.
SHIM="$OUT/host-shims/wasi-stat-mode.o"
mkdir -p "$(dirname "$SHIM")"
"$WASI_SDK/bin/clang" --target=$HOST -pthread -O2 -c "$ROOT/toolchain/host-shims/wasi-stat-mode.c" -o "$SHIM.tmp"
cmp -s "$SHIM.tmp" "$SHIM" && rm "$SHIM.tmp" || mv "$SHIM.tmp" "$SHIM"
# std's unwind crate links -lunwind for wasi + panic=unwind (WP-07). wasi-sdk has it only in the eh
# multilib dir; a dir holding just that library keeps the eh libc++ (which LLVM wasn't built against) out.
EHLIB="$OUT/host-shims/eh-lib"
mkdir -p "$EHLIB"
ln -sf "$WASI_SDK/share/wasi-sysroot/lib/$HOST/eh/libunwind.a" "$EHLIB/libunwind.a"

cat > "$OUT/bootstrap.toml" <<EOF
# Generated by toolchain/build-rustc.sh. Used as: ./x build --config build/rustc-wasm/bootstrap.toml
change-id = "ignore"

[build]
build-dir = "$OUT/build"
rustc = "$STAGE0/bin/rustc"
cargo = "$STABLE/bin/cargo"
# Stage 0 is stable $TAG itself, building the same version for a new host.
local-rebuild = true
description = ""
host = ["$HOST"]
target = ["$HOST"]
docs = false
extended = false
submodules = false
optimized-compiler-builtins = false

[llvm]
download-ci-llvm = false
use-libcxx = true

[rust]
channel = "stable"
codegen-backends = ["llvm"]
lld = false
llvm-tools = false
debug-assertions = false
overflow-checks = false
incremental = false
debuginfo-level = 0
jemalloc = false
deny-warnings = false

[target.$HOST]
llvm-config = "$LLVM/bin/llvm-config"
cc = "$ROOT/toolchain/bin/wasi-threads-clang"
cxx = "$ROOT/toolchain/bin/wasi-threads-clang++"
ar = "$WASI_SDK/bin/llvm-ar"
ranlib = "$WASI_SDK/bin/llvm-ranlib"
linker = "$ROOT/toolchain/bin/wasi-threads-clang"
wasi-root = "$WASI_SDK/share/wasi-sysroot"
# Flags for rustc.wasm itself (never the wasm32-wasip1 target spec users see): link against
# wasi-sdk's libc/libc++ (what LLVM was built against) instead of rustup's self-contained copy;
# LLVM uses mmap (emulated), needs up to 4 GiB of memory and a big stack. rustc_llvm's build
# script adds -lc++ but not -lc++abi, which holds operator new/delete in wasi-sdk.
# LLVM's DynamicLibrary.cpp calls dlopen & co.; wasi-libc's libdl provides stubs that fail cleanly.
# The stat shim gives files permission bits, without which std calls every file read-only.
# panic=unwind with Wasm exception handling (exnref, the target's -wasm-use-legacy-eh=false): rustc
# reports fatal errors by unwinding, which traps under panic=abort (WP-07). This also rebuilds std.
# Here rather than in RUSTFLAGS_BOOTSTRAP, which bootstrap.py also applies to its own native build.
rustflags = ["-Clink-self-contained=no", "-Clink-arg=-lc++abi", "-Clink-arg=-ldl", "-Clink-arg=-lwasi-emulated-mman",
             "-Clink-arg=-Wl,--max-memory=4294967296", "-Clink-arg=-Wl,-z,stack-size=8388608",
             "-Clink-arg=$SHIM", "-Clink-arg=-Wl,--wrap=stat,--wrap=lstat,--wrap=fstat,--wrap=fstatat",
             "-Cpanic=unwind", "-Ctarget-feature=+exception-handling", "-L$EHLIB"]
EOF
echo "wrote $OUT/bootstrap.toml"
[ "${1:-}" = config ] && exit 0

# The C/C++ parts (rustc_llvm's wrapper, cc-built crates) must match how LLVM was compiled.
export CFLAGS_wasm32_wasip1_threads="-pthread -D_WASI_EMULATED_MMAN"
export CXXFLAGS_wasm32_wasip1_threads="-pthread -D_WASI_EMULATED_MMAN"

cd "$RUST"
./x build --config "$OUT/bootstrap.toml" --stage 1 compiler/rustc -j 10
